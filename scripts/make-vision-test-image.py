#!/usr/bin/env python3
"""Write the fixed vision test image: 448x448 RGB PNG, fully synthetic.

White background, the word HELLO in black block letters (a 5x7 pixel font
drawn here, no font file), and three filled shapes: a red circle, a blue
square and a green triangle. Pure Python (zlib only), deterministic, so the
committed PNG can be regenerated byte for byte:

    python3 scripts/make-vision-test-image.py testdata/vision/hello-shapes-448.png
"""
import struct, sys, zlib

W = H = 448
FONT = {  # 5 x 7, '#' = ink
    'H': ["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
    'E': ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
    'L': ["#....", "#....", "#....", "#....", "#....", "#....", "#####"],
    'O': [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
}

def main(path):
    px = [[(255, 255, 255)] * W for _ in range(H)]
    def put(x, y, c):
        if 0 <= x < W and 0 <= y < H:
            px[y][x] = c
    # The word: cell 10 px, letters 50 x 70, 10 px apart: 5*50 + 4*10 = 290 wide.
    word, cell, gap = "HELLO", 10, 10
    x0, y0 = (W - (len(word) * 5 * cell + (len(word) - 1) * gap)) // 2, 50
    for i, ch in enumerate(word):
        for r, row in enumerate(FONT[ch]):
            for c, bit in enumerate(row):
                if bit == '#':
                    for dy in range(cell):
                        for dx in range(cell):
                            put(x0 + i * (5 * cell + gap) + c * cell + dx, y0 + r * cell + dy, (0, 0, 0))
    # Shapes, each about 100 px, on one row below the word.
    cy = 300
    for y in range(H):  # red circle, centre (94, cy), radius 50
        for x in range(W):
            if (x - 94) ** 2 + (y - cy) ** 2 <= 50 ** 2:
                put(x, y, (220, 30, 30))
    for y in range(cy - 50, cy + 50):  # blue square, 100 x 100
        for x in range(174, 274):
            put(x, y, (30, 60, 220))
    for y in range(cy - 50, cy + 50):  # green triangle, apex up, base 110
        half = (y - (cy - 50)) * 55 // 100
        for x in range(354 - half, 354 + half + 1):
            put(x, y, (30, 160, 60))
    raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in px)
    def chunk(tag, data):
        return struct.pack('>I', len(data)) + tag + data + struct.pack('>I', zlib.crc32(tag + data) & 0xffffffff)
    png = (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0))
           + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))
    with open(path, 'wb') as f:
        f.write(png)

if __name__ == '__main__':
    main(sys.argv[1])
